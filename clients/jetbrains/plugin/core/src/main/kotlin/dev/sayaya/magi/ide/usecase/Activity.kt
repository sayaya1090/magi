package dev.sayaya.magi.ide.usecase

/**
 * 컴패니언이 지금 무엇인가. **화면 둘이 같은 답을 쓰라고 있는 갈래다.**
 *
 * 이 판정은 원래 어디에도 없었고 화면마다 손으로 한 벌씩 적혀 있었다 — 상태 표시줄의 `label` 과
 * 우측 판의 `paint` 가 각자 `when` 을 썼다. 둘 다 IDE 플랫폼을 안 만지는데 플랫폼 모듈에 있어서
 * (`intellij` 에는 테스트 소스셋이 없다) **어느 쪽도 잴 수 없는 자리**였고, 그래서 둘은 이미
 * 갈라져 있었다:
 *
 * - 우측 판: `doing` 이 null 이면 "도는 것 없음" — 안 말했다는 뜻으로 그렸다.
 * - 상태 표시줄: 같은 자리에서 **"쉬는 중"** — 데몬이 한 적 없는 말을 화면이 지어냈다.
 *
 * 갈라진 쪽이 하필 [Companion.Facts] 의 주석이 **하지 말라고 이름 대어 적어 둔 것**이다:
 * *"`doing` 이 null 이면 「이 데몬이 안 말해 줬다」이고 화면은 그것을 「쉬는 중」으로 그리면 안
 * 된다"*. 규칙을 두 벌 적으면 한 벌이 조용히 틀리고, 틀린 쪽이 안 재지는 쪽이면 아무도 안 운다.
 *
 * **글자는 안 담는다.** [Level] 은 라벨 한 자리에 그대로 찍히는 물건이라 `text` 를 들지만, 이건
 * 화면 둘이 서로 다른 폭으로 그린다(눈꼬리의 한 줄 대 판의 한 칸). 여기서 글자를 정하면 둘 중
 * 하나는 자기에게 안 맞는 문장을 받는다. **정하는 것은 여기고 쓰는 것은 화면이다.**
 *
 * 갈래를 나누는 기준은 [Level] 과 같다: 보는 사람이 할 일이 다르면 갈래다.
 */
sealed interface Activity {

    /** 사람에게 물어 놓고 서 있다. 할 일: 답한다. 답하기 전에는 아무것도 안 나아간다. */
    data object Waiting : Activity

    /**
     * 무언가 돌고 있다. 할 일: 없다(기다린다).
     *
     * [what] 은 도는 툴이 **자기에 대해 마지막으로 말한 것**이다. 판은 이걸 그대로 그리고
     * 표시줄은 폭이 없어 안 그린다 — 그래서 값을 여기 싣고 쓸지는 화면이 정한다.
     */
    data class Doing(val what: String) : Activity

    /**
     * 데몬이 무엇을 하는지 **말하지 않았다.** 할 일: 없다 — 다만 화면은 이것을 「쉬는 중」으로
     * 그리면 안 된다. 모름과 없음이 같은 값(null)으로 오기 때문에, 없음이라고 말하는 순간
     * 화면은 아는 척을 한다.
     */
    data object Unsaid : Activity

    companion object {
        /**
         * **순서가 계약이다.** 기다림이 돎을 이긴다 — 사람을 막아 세운 컴패니언도 턴 안이라
         * `doing` 이 같이 실려 오고([Companion.turnIsOpen] 이 같은 사실을 쓴다), 그때 돎을
         * 먼저 보면 화면은 「도는 중」이라 적는다. 사람이 답해 줘야 나아가는 상태가 화면에서
         * **저절로 끝날 상태**와 같아 보이는 것이 이 순서를 뒤집었을 때 나는 일이다.
         */
        fun of(f: Companion.Facts): Activity = when {
            f.waiting != null -> Waiting
            f.doing != null -> Doing(f.doing)
            else -> Unsaid
        }
    }
}
