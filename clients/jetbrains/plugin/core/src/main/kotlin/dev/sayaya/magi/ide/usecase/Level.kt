package dev.sayaya.magi.ide.usecase

/**
 * 상태 라벨에 설 수 있는 말. **수준만 있다** — 「지금 무엇인가」이지 「방금 무엇을 했고 어떻게
 * 됐나」가 아니다. 사건은 전사로 간다(`report`).
 *
 * **왜 `String` 이 아닌가.** 라벨이 글자를 받으면 어떤 문장이든 설 수 있고, 그러면 「여기엔
 * 수준만 쓴다」를 붙드는 것은 주석과 **자리를 세는 시험**뿐이다. 셈은 도달이지 계약의 증명이
 * 아니다: 쓰는 자리가 둘인 채로 그중 하나가 조용히 사건으로 바뀌면 셈은 그대로 둘이라 아무도
 * 안 운다. 갈래로 만들면 그 문장을 **쓸 수가 없다** — 사건에는 여기 들어올 이름이 없다.
 *
 * 그래서 셈 대신 남은 규칙은 하나다: **라벨에 글자를 넣는 문은 하나여야 한다**(`SourceTextTest`).
 * 그 문이 [Level] 만 받으므로, 문이 하나인 것과 사건이 못 들어오는 것이 같이 선다. 호출자는
 * 얼마든지 늘어도 된다 — 늘어나는 것이 규칙을 약하게 하지 않는다.
 *
 * 갈래를 나누는 기준은 `End` 와 같다: **보는 사람이 할 일이 다르면 갈래다.**
 */
sealed interface Level {

    /** 라벨에 그대로 찍히는 글자. */
    val text: String

    /** 컴패니언이 붙어 있고 사람에게 물을 것이 없다. 할 일: 없다. */
    data object Attached : Level {
        override val text get() = "컴패니언이 붙어 있다."
    }

    /** 컴패니언이 물어 놓고 서 있다. 할 일: 답한다. */
    data object Waiting : Level {
        override val text get() = "사람을 기다리는 중이다."
    }

    /**
     * 데몬에 못 닿는다. 할 일: 데몬을 켠다(또는 왜 안 켜지는지 본다).
     *
     * [why] 는 **닿기를 시도한 쪽이 갈래를 접어 준 문장 그대로**다. 여기서 다시 짓지 않는다 —
     * 사유를 아는 것은 시도한 쪽이고, 접힌 것을 화면에서 펴면 모르는 것을 아는 척하게 된다.
     *
     * **여기가 남은 구멍이다.** 이 갈래만 글자를 받으므로 사건을 이 이름으로 싣는 것이 아직
     * 가능하다 — 다만 그러려면 「닿지 못했다」는 이름으로 거짓말을 해야 하고, 그건 diff 에
     * 보인다. 완전히 막으려면 `Workspace.onDaemon` 이 글자 대신 갈래를 돌려줘야 하는데, 그
     * 콜백은 창 둘이 같이 쓴다.
     */
    data class Unreachable(val why: String) : Level {
        override val text get() = why
    }
}
