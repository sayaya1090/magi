package dev.sayaya.magi.ide.usecase

/**
 * 지금 무엇인가 — **수준**이다. 「방금 무엇을 했고 어떻게 됐나」가 아니다(사건은 전사로 간다).
 *
 * **글자를 안 든다.** 예전엔 갈래마다 `text` 가 있었는데, 이 파일은 `core` 에 살고 `core` 는
 * 번들에 못 닿는다 — 그래서 그 글자는 영영 한국어였고, 영어 IDE 의 화면에 「컴패니언이 붙어
 * 있다」가 떴다(사용자 실측 2026-09-01). 화면 글자를 여기 두는 한 그 결함은 구조적으로 다시
 * 난다. 수준은 **갈래**로만 남기고, 그리는 것은 번들에 닿는 쪽이 한다.
 *
 * 갈래를 나누는 기준은 `End` 와 같다: **보는 사람이 할 일이 다르면 갈래다.**
 */
sealed interface Level {

    /** 컴패니언이 붙어 있고 사람에게 물을 것이 없다. 할 일: 없다. */
    data object Attached : Level

    /** 컴패니언이 물어 놓고 서 있다. 할 일: 답한다. */
    data object Waiting : Level

    /**
     * 데몬에 못 닿는다. 할 일: 데몬을 켠다(또는 왜 안 켜지는지 본다).
     *
     * [why] 는 **닿기를 시도한 쪽이 갈래를 접어 준 문장 그대로**다. 여기서 다시 짓지 않는다 —
     * 사유를 아는 것은 시도한 쪽이고, 접힌 것을 화면에서 펴면 모르는 것을 아는 척하게 된다.
     * 그 문장은 이미 번들을 지나온 것이라 화면 글자로 서도 된다.
     */
    data class Unreachable(val why: String) : Level
}
