import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync('clients/powerpoint/addin/src/adapter/OfficeHand.js', 'utf8');
const i = src.indexOf('const GEOMETRY = new Map(Object.entries({');
const j = src.indexOf('}));', i);
const body = src.slice(i, j);
const pairs = [...body.matchAll(/(?:^|[\s{,])([A-Za-z0-9가-힣_]+)\s*:\s*'([A-Za-z0-9]+)'/gm)].map((m) => [m[1], m[2]]);
const canon = [...new Set(pairs.map((p) => p[1]))].sort();

const MSO = {
  arc: 'msoShapeArc', bentArrow: 'msoShapeBentArrow', bevel: 'msoShapeBevel', blockArc: 'msoShapeBlockArc',
  can: 'msoShapeCan', chevron: 'msoShapeChevron', chord: 'msoShapeChord', cloud: 'msoShapeCloud',
  cloudCallout: 'msoShapeCloudCallout', cube: 'msoShapeCube', curvedRightArrow: 'msoShapeCurvedRightArrow',
  diamond: 'msoShapeDiamond', donut: 'msoShapeDonut', downArrow: 'msoShapeDownArrow', ellipse: 'msoShapeOval',
  flowChartDecision: 'msoShapeFlowchartDecision', flowChartDocument: 'msoShapeFlowchartDocument',
  flowChartInputOutput: 'msoShapeFlowchartData', flowChartProcess: 'msoShapeFlowchartProcess',
  flowChartTerminator: 'msoShapeFlowchartTerminator', frame: 'msoShapeFrame', heart: 'msoShapeHeart',
  heptagon: 'msoShapeHeptagon', hexagon: 'msoShapeHexagon', homePlate: 'msoShapePentagon',
  leftArrow: 'msoShapeLeftArrow', leftRightArrow: 'msoShapeLeftRightArrow', lightningBolt: 'msoShapeLightningBolt',
  mathEqual: 'msoShapeMathEqual', mathMinus: 'msoShapeMathMinus', mathMultiply: 'msoShapeMathMultiply',
  mathPlus: 'msoShapeMathPlus', moon: 'msoShapeMoon', noSmoking: 'msoShapeNoSymbol', octagon: 'msoShapeOctagon',
  parallelogram: 'msoShapeParallelogram', pentagon: 'msoShapeRegularPentagon', pie: 'msoShapePie',
  plaque: 'msoShapePlaque', rectangle: 'msoShapeRectangle', rightArrow: 'msoShapeRightArrow',
  rightTriangle: 'msoShapeRightTriangle', roundRectangle: 'msoShapeRoundedRectangle', smileyFace: 'msoShapeSmileyFace',
  star10: 'msoShape10pointStar', star12: 'msoShape12pointStar', star4: 'msoShape4pointStar',
  star5: 'msoShape5pointStar', star6: 'msoShape6pointStar', star8: 'msoShape8pointStar', sun: 'msoShapeSun',
  teardrop: 'msoShapeTear', trapezoid: 'msoShapeTrapezoid', triangle: 'msoShapeIsoscelesTriangle',
  upArrow: 'msoShapeUpArrow', upDownArrow: 'msoShapeUpDownArrow', wedgeEllipseCallout: 'msoShapeOvalCallout',
  wedgeRectCallout: 'msoShapeRectangularCallout', wedgeRoundRectCallout: 'msoShapeRoundedRectangularCallout',
};
const missing = canon.filter((c) => c !== 'line' && !MSO[c]);
if (missing.length) { console.error('MsoAutoShapeType 짝이 없는 도형:', missing.join(' ')); process.exit(1); }

const norm = (s) => s.toLowerCase().replace(/[\s_-]/g, '');
const alias = new Map();
for (const c of canon) alias.set(norm(c), c);
for (const [k, v] of pairs) alias.set(norm(k), v);
alias.set('textbox', 'textbox');

const lines = [];
lines.push('// <auto-generated> 이 파일은 tools/gen-shapekinds 가 OfficeHand.js 의 GEOMETRY 에서 만든다. 손으로 고치지 않는다.');
lines.push('// 두 손이 같은 도형 어휘를 쓰게 하는 자리다 — 웹 손(Office.js)과 COM 손(Office 2021)이 갈리면');
lines.push('// 같은 이름이 한쪽에선 별이고 한쪽에선 네모가 된다. 실측 2026-09-26: 갈려 있었다.');
lines.push('#nullable enable');
lines.push('using Office = Microsoft.Office.Core;');
lines.push('');
lines.push('namespace Magi.Ppt.Hand;');
lines.push('');
lines.push('/// <summary>도형 이름표 — 사람·모델이 부르는 말에서 Office 의 도형 종류까지.</summary>');
lines.push('public static class ShapeKinds');
lines.push('{');
lines.push('    /// <summary>별명·표준명(대소문자·공백·밑줄 무시) → 표준명.</summary>');
lines.push('    public static readonly Dictionary<string, string> Alias = new()');
lines.push('    {');
for (const [k, v] of [...alias.entries()].sort()) lines.push(`        ["${k}"] = "${v}",`);
lines.push('    };');
lines.push('');
lines.push('    /// <summary>표준명 → Office 도형. textbox 와 line 은 부르는 길이 달라 여기 없다.</summary>');
lines.push('    public static readonly Dictionary<string, Office.MsoAutoShapeType> Mso = new()');
lines.push('    {');
for (const c of canon) if (c !== 'line') lines.push(`        ["${c}"] = Office.MsoAutoShapeType.${MSO[c]},`);
lines.push('    };');
lines.push('');
lines.push('    /// <summary>아는 표준명들, 사람에게 보여 줄 순서로.</summary>');
lines.push('    public static IEnumerable<string> Names => Mso.Keys.Concat(new[] { "line", "textbox" }).OrderBy(x => x, StringComparer.Ordinal);');
lines.push('');
lines.push('    /// <summary>부르는 말을 표준명으로. 모르는 이름은 <b>가장 가까운 것을 짚어</b> 거절한다.</summary>');
lines.push('    public static string Resolve(string? kind)');
lines.push('    {');
lines.push('        var raw = (kind ?? "").Trim();');
lines.push('        if (raw.Length == 0) return "textbox";');
lines.push('        var key = new string(raw.ToLowerInvariant().Where(c => c is not (\' \' or \'_\' or \'-\')).ToArray());');
lines.push('        if (Alias.TryGetValue(key, out var got)) return got;');
lines.push('        var near = Names.Where(n => { var f = n.ToLowerInvariant();');
lines.push('            return f.Contains(key) || key.Contains(f)');
lines.push('                || f.StartsWith(key[..Math.Min(5, key.Length)]) || key.StartsWith(f[..Math.Min(5, f.Length)]); })');
lines.push('            .Take(5).ToList();');
lines.push('        throw new HandError($"{raw} 는 이 손이 아는 도형이 아닙니다"');
lines.push('            + (near.Count > 0 ? $" — 혹시 {string.Join(" · ", near)} 입니까?" : "")');
lines.push('            + " — 아는 것: " + string.Join(", ", Names));');
lines.push('    }');
lines.push('}');
writeFileSync('clients/powerpoint/hand-com/src/ShapeKinds.cs', lines.join('\n') + '\n');
console.log('wrote ShapeKinds.cs — 표준명', canon.length, '· 별명', alias.size);
